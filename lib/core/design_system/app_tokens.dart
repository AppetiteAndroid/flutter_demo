import 'package:flutter/material.dart';

abstract final class AppPalette {
  static const brand500 = Color(0xFF635BFF),
      brand700 = Color(0xFF4338CA),
      accent500 = Color(0xFF06B6D4);
  static const neutral0 = Color(0xFFFFFFFF),
      neutral50 = Color(0xFFF8FAFC),
      neutral100 = Color(0xFFF1F5F9),
      neutral300 = Color(0xFFCBD5E1),
      neutral500 = Color(0xFF64748B),
      neutral700 = Color(0xFF334155),
      neutral900 = Color(0xFF0F172A),
      neutral1000 = Color(0xFF020617);
  static const red500 = Color(0xFFEF4444),
      green500 = Color(0xFF22C55E),
      orange500 = Color(0xFFF59E0B),
      blue500 = Color(0xFF3B82F6);
}

abstract final class AppSpacing {
  static const xxs = 4.0,
      xs = 8.0,
      sm = 12.0,
      md = 16.0,
      lg = 24.0,
      xl = 32.0,
      xxl = 48.0;
}

abstract final class AppRadius {
  static const xs = 4.0,
      sm = 8.0,
      md = 12.0,
      lg = 16.0,
      xl = 24.0,
      full = 999.0;
}

abstract final class AppIconSize {
  static const small = 16.0, medium = 24.0, large = 32.0;
}

abstract final class AppFonts {
  static const gilroy = 'Gilroy', ceraRound = 'CeraRound';
  static const String? fallback = null;
}

class AppColors extends ThemeExtension<AppColors> {
  const AppColors({
    required this.brandPrimary,
    required this.brandSecondary,
    required this.backgroundPrimary,
    required this.backgroundSecondary,
    required this.surfacePrimary,
    required this.surfaceSecondary,
    required this.surfaceElevated,
    required this.textPrimary,
    required this.textSecondary,
    required this.textTertiary,
    required this.textInverse,
    required this.textDisabled,
    required this.iconPrimary,
    required this.iconSecondary,
    required this.iconInverse,
    required this.iconDisabled,
    required this.borderPrimary,
    required this.borderSecondary,
    required this.borderFocused,
    required this.success,
    required this.warning,
    required this.error,
    required this.info,
    required this.stateDisabled,
    required this.statePressed,
    required this.stateOverlay,
  });
  final Color brandPrimary,
      brandSecondary,
      backgroundPrimary,
      backgroundSecondary,
      surfacePrimary,
      surfaceSecondary,
      surfaceElevated,
      textPrimary,
      textSecondary,
      textTertiary,
      textInverse,
      textDisabled,
      iconPrimary,
      iconSecondary,
      iconInverse,
      iconDisabled,
      borderPrimary,
      borderSecondary,
      borderFocused,
      success,
      warning,
      error,
      info,
      stateDisabled,
      statePressed,
      stateOverlay;
  static const light = AppColors(
    brandPrimary: AppPalette.brand500,
    brandSecondary: AppPalette.accent500,
    backgroundPrimary: AppPalette.neutral0,
    backgroundSecondary: AppPalette.neutral50,
    surfacePrimary: AppPalette.neutral0,
    surfaceSecondary: AppPalette.neutral100,
    surfaceElevated: AppPalette.neutral0,
    textPrimary: AppPalette.neutral900,
    textSecondary: AppPalette.neutral700,
    textTertiary: AppPalette.neutral500,
    textInverse: AppPalette.neutral0,
    textDisabled: AppPalette.neutral500,
    iconPrimary: AppPalette.neutral900,
    iconSecondary: AppPalette.neutral500,
    iconInverse: AppPalette.neutral0,
    iconDisabled: AppPalette.neutral300,
    borderPrimary: AppPalette.neutral300,
    borderSecondary: AppPalette.neutral100,
    borderFocused: AppPalette.brand500,
    success: AppPalette.green500,
    warning: AppPalette.orange500,
    error: AppPalette.red500,
    info: AppPalette.blue500,
    stateDisabled: AppPalette.neutral100,
    statePressed: AppPalette.brand700,
    stateOverlay: Color(0x14000000),
  );
  static const dark = AppColors(
    brandPrimary: Color(0xFF8B85FF),
    brandSecondary: Color(0xFF22D3EE),
    backgroundPrimary: AppPalette.neutral1000,
    backgroundSecondary: AppPalette.neutral900,
    surfacePrimary: AppPalette.neutral900,
    surfaceSecondary: AppPalette.neutral700,
    surfaceElevated: AppPalette.neutral700,
    textPrimary: AppPalette.neutral50,
    textSecondary: AppPalette.neutral300,
    textTertiary: AppPalette.neutral500,
    textInverse: AppPalette.neutral900,
    textDisabled: AppPalette.neutral500,
    iconPrimary: AppPalette.neutral50,
    iconSecondary: AppPalette.neutral300,
    iconInverse: AppPalette.neutral900,
    iconDisabled: AppPalette.neutral500,
    borderPrimary: AppPalette.neutral700,
    borderSecondary: AppPalette.neutral900,
    borderFocused: Color(0xFF8B85FF),
    success: AppPalette.green500,
    warning: AppPalette.orange500,
    error: AppPalette.red500,
    info: AppPalette.blue500,
    stateDisabled: AppPalette.neutral700,
    statePressed: AppPalette.brand700,
    stateOverlay: Color(0x24FFFFFF),
  );
  @override
  AppColors copyWith({
    Color? brandPrimary,
    Color? brandSecondary,
    Color? backgroundPrimary,
    Color? backgroundSecondary,
    Color? surfacePrimary,
    Color? surfaceSecondary,
    Color? surfaceElevated,
    Color? textPrimary,
    Color? textSecondary,
    Color? textTertiary,
    Color? textInverse,
    Color? textDisabled,
    Color? iconPrimary,
    Color? iconSecondary,
    Color? iconInverse,
    Color? iconDisabled,
    Color? borderPrimary,
    Color? borderSecondary,
    Color? borderFocused,
    Color? success,
    Color? warning,
    Color? error,
    Color? info,
    Color? stateDisabled,
    Color? statePressed,
    Color? stateOverlay,
  }) => AppColors(
    brandPrimary: brandPrimary ?? this.brandPrimary,
    brandSecondary: brandSecondary ?? this.brandSecondary,
    backgroundPrimary: backgroundPrimary ?? this.backgroundPrimary,
    backgroundSecondary: backgroundSecondary ?? this.backgroundSecondary,
    surfacePrimary: surfacePrimary ?? this.surfacePrimary,
    surfaceSecondary: surfaceSecondary ?? this.surfaceSecondary,
    surfaceElevated: surfaceElevated ?? this.surfaceElevated,
    textPrimary: textPrimary ?? this.textPrimary,
    textSecondary: textSecondary ?? this.textSecondary,
    textTertiary: textTertiary ?? this.textTertiary,
    textInverse: textInverse ?? this.textInverse,
    textDisabled: textDisabled ?? this.textDisabled,
    iconPrimary: iconPrimary ?? this.iconPrimary,
    iconSecondary: iconSecondary ?? this.iconSecondary,
    iconInverse: iconInverse ?? this.iconInverse,
    iconDisabled: iconDisabled ?? this.iconDisabled,
    borderPrimary: borderPrimary ?? this.borderPrimary,
    borderSecondary: borderSecondary ?? this.borderSecondary,
    borderFocused: borderFocused ?? this.borderFocused,
    success: success ?? this.success,
    warning: warning ?? this.warning,
    error: error ?? this.error,
    info: info ?? this.info,
    stateDisabled: stateDisabled ?? this.stateDisabled,
    statePressed: statePressed ?? this.statePressed,
    stateOverlay: stateOverlay ?? this.stateOverlay,
  );
  @override
  AppColors lerp(covariant AppColors? other, double t) {
    if (other == null) return this;
    Color l(Color a, Color b) => Color.lerp(a, b, t)!;
    return AppColors(
      brandPrimary: l(brandPrimary, other.brandPrimary),
      brandSecondary: l(brandSecondary, other.brandSecondary),
      backgroundPrimary: l(backgroundPrimary, other.backgroundPrimary),
      backgroundSecondary: l(backgroundSecondary, other.backgroundSecondary),
      surfacePrimary: l(surfacePrimary, other.surfacePrimary),
      surfaceSecondary: l(surfaceSecondary, other.surfaceSecondary),
      surfaceElevated: l(surfaceElevated, other.surfaceElevated),
      textPrimary: l(textPrimary, other.textPrimary),
      textSecondary: l(textSecondary, other.textSecondary),
      textTertiary: l(textTertiary, other.textTertiary),
      textInverse: l(textInverse, other.textInverse),
      textDisabled: l(textDisabled, other.textDisabled),
      iconPrimary: l(iconPrimary, other.iconPrimary),
      iconSecondary: l(iconSecondary, other.iconSecondary),
      iconInverse: l(iconInverse, other.iconInverse),
      iconDisabled: l(iconDisabled, other.iconDisabled),
      borderPrimary: l(borderPrimary, other.borderPrimary),
      borderSecondary: l(borderSecondary, other.borderSecondary),
      borderFocused: l(borderFocused, other.borderFocused),
      success: l(success, other.success),
      warning: l(warning, other.warning),
      error: l(error, other.error),
      info: l(info, other.info),
      stateDisabled: l(stateDisabled, other.stateDisabled),
      statePressed: l(statePressed, other.statePressed),
      stateOverlay: l(stateOverlay, other.stateOverlay),
    );
  }
}
